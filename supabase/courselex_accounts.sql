begin;
create schema if not exists courselex_private;
revoke all on schema courselex_private from public, anon;
grant usage on schema courselex_private to authenticated;
create table public.user_courses (
 id uuid primary key default gen_random_uuid(), user_id uuid not null default auth.uid() references auth.users(id),
 name text not null check(length(btrim(name)) between 1 and 120), code text not null default '' check(length(code)<=40),
 weeks integer not null default 13 check(weeks between 1 and 52), archived boolean not null default false,
 created_at timestamptz not null default now(), unique(id,user_id)
);
create index user_courses_owner on public.user_courses(user_id);
create table public.user_vocabulary (
 id bigint generated by default as identity primary key, user_id uuid not null default auth.uid() references auth.users(id),
 course_id uuid not null, week integer not null check(week between 1 and 52),
 english text not null check(length(btrim(english)) between 1 and 200), chinese text not null check(length(btrim(chinese)) between 1 and 500),
 word_type text not null default 'Professional term', status text not null default 'new' check(status in ('new','known','unknown')),
 wrong_count integer not null default 0 check(wrong_count>=0), seen_count integer not null default 0 check(seen_count>=0),
 legacy_id bigint, created_at timestamptz not null default now(), unique(user_id,legacy_id),
 foreign key(course_id,user_id) references public.user_courses(id,user_id) on delete restrict
);
create index user_vocabulary_owner_course on public.user_vocabulary(user_id,course_id,week);
create index user_vocabulary_course_fk on public.user_vocabulary(course_id,user_id);
create unique index user_vocabulary_term on public.user_vocabulary(user_id,course_id,week,lower(btrim(english)));
create table public.user_upload_jobs (
 id text primary key, user_id uuid not null references auth.users(id), course uuid not null, week integer not null check(week between 1 and 52),
 filename text not null, nonce text not null, status text not null default 'awaiting_upload' check(status in ('awaiting_upload','initializing','processing','failed')),
 response_id text, error_message text, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 foreign key(course,user_id) references public.user_courses(id,user_id) on delete restrict
);
create index user_upload_jobs_course_fk on public.user_upload_jobs(course,user_id);
create index user_upload_jobs_owner on public.user_upload_jobs(user_id,created_at);
alter table public.user_courses enable row level security;
alter table public.user_vocabulary enable row level security;
alter table public.user_upload_jobs enable row level security;
create policy courses_owner on public.user_courses for all to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
create policy vocabulary_owner on public.user_vocabulary for all to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
-- Jobs are server-only; the handler verifies owner and signed job credentials on every request.
revoke all on public.user_courses,public.user_vocabulary,public.user_upload_jobs from anon,authenticated;
grant select,insert,update on public.user_courses to authenticated;
grant select,insert,update,delete on public.user_vocabulary to authenticated;
grant usage,select on sequence public.user_vocabulary_id_seq to authenticated;
grant all on public.user_courses,public.user_vocabulary,public.user_upload_jobs to service_role;
grant usage,select on sequence public.user_vocabulary_id_seq to service_role;
create function public.check_user_word_week() returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
declare n integer; a boolean;
begin
 select weeks,archived into n,a from public.user_courses where id=new.course_id and user_id=new.user_id for share;
 if n is null or a or new.week>n then raise exception 'Course is archived or week is out of range'; end if;
 return new;
end;$$;
create trigger user_word_week before insert or update of course_id,week,user_id on public.user_vocabulary for each row execute function public.check_user_word_week();
create function public.check_course_weeks() returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
begin
 if new.weeks<old.weeks and exists(select 1 from public.user_vocabulary where course_id=old.id and week>new.weeks) then raise exception 'Existing words require these weeks'; end if;
 return new;
end;$$;
create trigger user_course_weeks before update of weeks on public.user_courses for each row execute function public.check_course_weeks();
create function public.import_user_vocabulary(p_course uuid,p_week integer,p_terms jsonb) returns jsonb language plpgsql security invoker set search_path=public,pg_temp as $$
declare n integer; total integer;
begin
 if auth.uid() is null then raise exception 'Sign in required'; end if;
 if jsonb_typeof(p_terms) is distinct from 'array' or jsonb_array_length(p_terms)>1500 then raise exception 'Invalid terms'; end if;
 if not exists(select 1 from public.user_courses where id=p_course and user_id=auth.uid() and not archived and p_week between 1 and weeks) then raise exception 'Invalid course or week'; end if;
 perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text||p_course::text||p_week::text,0));
 with candidates as (select distinct on(lower(btrim(t->>'english'))) btrim(t->>'english') en,btrim(t->>'chinese') zh from jsonb_array_elements(p_terms) t order by lower(btrim(t->>'english'))), added as (
 insert into public.user_vocabulary(user_id,course_id,week,english,chinese) select auth.uid(),p_course,p_week,en,zh from candidates on conflict do nothing returning id
 ) select count(*) into n from added;
 select count(distinct lower(btrim(t->>'english'))) into total from jsonb_array_elements(p_terms) t;
 return jsonb_build_object('inserted',n,'skipped',total-n);
end;$$;
revoke all on function public.import_user_vocabulary(uuid,integer,jsonb) from public,anon;
grant execute on function public.import_user_vocabulary(uuid,integer,jsonb) to authenticated;
-- Immutable archival source. No original rows are updated or deleted.
revoke all on public.vocabulary_data from anon,authenticated;
revoke execute on function public.import_course_vocabulary(text,integer,jsonb) from anon,authenticated;
drop policy "Allow vocabulary access" on public.vocabulary_data;
create table courselex_private.legacy_migrations(user_id uuid primary key references auth.users(id), migrated_at timestamptz not null default now());
alter table courselex_private.legacy_migrations enable row level security;
create function courselex_private.copy_legacy() returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare uid uuid:=auth.uid(); c record; cid uuid; n integer:=0; k integer;
begin
 if uid is null or not exists(select 1 from auth.users where id=uid and lower(email)='ywang8377-c@my.cityu.edu.hk' and email_confirmed_at is not null) then raise exception 'Only the verified legacy owner can migrate'; end if;
 perform pg_advisory_xact_lock(hashtextextended('courselex-legacy-migration',0));
 if exists(select 1 from courselex_private.legacy_migrations where user_id=uid) then return jsonb_build_object('already_migrated',true); end if;
 if exists(select 1 from courselex_private.legacy_migrations) then raise exception 'Legacy data already bound to another account'; end if;
 for c in select course,greatest(13,max(week)) weeks from public.vocabulary_data group by course loop
 insert into public.user_courses(user_id,name,code,weeks) values(uid,case c.course when 'COM5103' then 'Policy and Regulations of New Media' when 'COM5101' then 'Communication Fundamental' when 'COM5501' then 'Internet Communication' when 'COM5104' then 'Research Methods for Communication and New Media' else c.course end,c.course,c.weeks) returning id into cid;
 insert into public.user_vocabulary(user_id,course_id,week,english,chinese,word_type,status,wrong_count,seen_count,legacy_id)
 select uid,cid,week,english,chinese,coalesce(word_type,'Professional term'),case when status in ('known','unknown') then status else 'new' end,greatest(coalesce(wrong_count,0),0),greatest(coalesce(seen_count,0),0),id from public.vocabulary_data where course=c.course order by id on conflict do nothing;
 get diagnostics k=row_count; n:=n+k;
 end loop;
 insert into courselex_private.legacy_migrations(user_id) values(uid);
 return jsonb_build_object('inserted',n);
end;$$;
revoke all on function courselex_private.copy_legacy() from public,anon;
grant execute on function courselex_private.copy_legacy() to authenticated;
create function public.migrate_legacy_vocabulary() returns jsonb language sql security invoker set search_path=public,pg_temp as $$ select courselex_private.copy_legacy(); $$;
revoke all on function public.migrate_legacy_vocabulary() from public,anon;
grant execute on function public.migrate_legacy_vocabulary() to authenticated;
revoke execute on function public.check_user_word_week(),public.check_course_weeks() from public,anon,authenticated;
create function public.check_upload_job_quota() returns trigger language plpgsql security invoker set search_path=public,pg_temp as $$
begin
 perform pg_advisory_xact_lock(hashtextextended('upload-quota:'||new.user_id::text,0));
 if (select count(*) from public.user_upload_jobs where user_id=new.user_id and created_at>now()-interval '24 hours')>=10 then raise exception 'Daily upload quota exceeded'; end if;
 return new;
end;$$;
create trigger upload_job_quota before insert on public.user_upload_jobs for each row execute function public.check_upload_job_quota();
revoke execute on function public.check_upload_job_quota() from public,anon,authenticated;
commit;
